#!/usr/bin/env python3
"""
Zero-dependency static blog index builder for Barry's Journal.
Reads all Markdown files in ./posts/*.md, parses YAML frontmatter,
and writes ./posts/posts.js (and ./posts/posts.json).
"""

import json
import math
import re
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent
POSTS_DIR = ROOT_DIR / "posts"


def parse_frontmatter(raw_text: str):
    """Parse simple --- frontmatter --- and return (metadata_dict, markdown_body)."""
    text = raw_text.replace("\r\n", "\n")
    if not text.startswith("---\n"):
        return {}, text.strip()

    end_idx = text.find("\n---\n", 4)
    if end_idx == -1:
        return {}, text.strip()

    header_block = text[4:end_idx]
    body = text[end_idx + 5 :].strip()

    meta = {}
    for line in header_block.split("\n"):
        line = line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, val = line.split(":", 1)
        meta[key.strip().lower()] = val.strip()

    return meta, body


def estimate_reading_time(text: str) -> str:
    words = len(re.findall(r"\w+", text))
    minutes = max(1, math.ceil(words / 200))
    return f"{minutes} min read"


def build_posts():
    POSTS_DIR.mkdir(parents=True, exist_ok=True)
    posts = []

    for md_file in sorted(POSTS_DIR.glob("*.md"), reverse=True):
        raw = md_file.read_text(encoding="utf-8")
        meta, body = parse_frontmatter(raw)

        slug = md_file.stem
        title = meta.get("title", slug.replace("-", " ").title())
        date = meta.get("date", "2026-10-29")
        tags_raw = meta.get("tags", "systems")
        tags = [t.strip() for t in tags_raw.split(",") if t.strip()]

        summary = meta.get("summary", "")
        if not summary:
            # Extract first non-heading paragraph as summary
            for para in body.split("\n\n"):
                p = para.strip()
                if p and not p.startswith("#") and not p.startswith("```"):
                    summary = re.sub(r"[*_`>#]", "", p)[:180]
                    break

        posts.append(
            {
                "slug": slug,
                "title": title,
                "date": date,
                "tags": tags,
                "summary": summary,
                "readingTime": estimate_reading_time(body),
                "body": body,
            }
        )

    # Sort by date descending, then slug descending
    posts.sort(key=lambda p: (p["date"], p["slug"]), reverse=True)

    json_payload = json.dumps(posts, indent=2, ensure_ascii=False)
    (POSTS_DIR / "posts.json").write_text(json_payload + "\n", encoding="utf-8")

    js_payload = (
        "// Auto-generated by build.py — Do not edit manually.\n"
        "// Edit or add Markdown files in ./posts/*.md and run: python3 build.py\n"
        f"window.JOURNAL_POSTS = {json_payload};\n"
    )
    (POSTS_DIR / "posts.js").write_text(js_payload, encoding="utf-8")
    print(f"[build.py] Built {len(posts)} post(s) -> posts/posts.js & posts/posts.json")


if __name__ == "__main__":
    build_posts()
